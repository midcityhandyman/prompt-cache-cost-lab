"""Regenerate the synthetic fixtures. Seeded, so the output is identical every run.

Nothing here comes from a real system. The "recorded" usage is invented to look
like a morning of help desk traffic: bursts of requests with idle gaps between.
"""

from __future__ import annotations

import json
import random
from pathlib import Path

FIXTURES = Path(__file__).resolve().parents[1] / "fixtures"
PREFIX_TOKENS = 6200  # stable system prompt + reference notes, the same on every request

# (requests in the burst, idle seconds before the burst starts)
BURSTS = [(12, 0), (10, 12 * 60), (14, 25 * 60), (12, 70 * 60)]


def make_usage(rng: random.Random) -> list[dict]:
    rows, t, number = [], 0.0, 1
    for size, idle in BURSTS:
        t += idle
        for _ in range(size):
            rows.append(
                {
                    "id": f"req-{number:03d}",
                    "t": round(t, 1),
                    "prefix_tokens": PREFIX_TOKENS,
                    "dynamic_tokens": rng.randint(150, 900),
                    "output_tokens": rng.randint(180, 650),
                }
            )
            number += 1
            t += rng.randint(20, 90)
    return rows


TOPICS = ["scheduling", "invoices", "warranty", "quotes", "access", "materials", "cleanup", "follow up"]
RULES = [
    "confirm the request back in one sentence before answering",
    "never promise a date that is not on the calendar",
    "offer the next two open slots when a slot is taken",
    "escalate to a human when the message mentions damage or safety",
    "keep the reply under 120 words unless a list is needed",
    "state what happens next and who does it",
]


def make_prompts(rng: random.Random) -> dict:
    notes = []
    for number in range(1, 61):
        topic = TOPICS[number % len(TOPICS)]
        rule = RULES[rng.randrange(len(RULES))]
        notes.append(
            f"Note {number:02d} ({topic}): When a message is about {topic}, {rule}. "
            f"If the sender asks twice about {topic}, restate the earlier answer first, "
            f"then add only what is new. Reference code SAMPLE-{1000 + number}."
        )
    system = (
        "You are the help desk assistant for a fictional service desk used only in this demo. "
        "Answer using the notes below. If the notes do not cover a question, say so.\n\n"
        + "\n".join(notes)
    )
    questions = [
        "Can I move my Tuesday visit to later in the week?",
        "I was sent the same invoice twice, which one do I pay?",
        "Is the work from last month still under warranty?",
        "How long is a written quote valid for?",
        "Nobody will be home, how does the crew get in?",
        "Who takes away the leftover materials when the job is done?",
    ]
    return {"_comment": "Synthetic prompt set for the replay runner. Invented text.", "system": system, "questions": questions}


def main() -> None:
    rng = random.Random(20261124)
    FIXTURES.mkdir(exist_ok=True)
    with open(FIXTURES / "usage_recorded.jsonl", "w", encoding="utf-8", newline="\n") as handle:
        handle.write("# SYNTHETIC token usage for one workload, recorded with no caching.\n")
        handle.write("# t = seconds since the first request. Generated by scripts/make_fixtures.py.\n")
        for row in make_usage(rng):
            handle.write(json.dumps(row) + "\n")
    with open(FIXTURES / "replay_prompts.json", "w", encoding="utf-8", newline="\n") as handle:
        json.dump(make_prompts(rng), handle, indent=2)
        handle.write("\n")
    print("fixtures written to", FIXTURES)


if __name__ == "__main__":
    main()
